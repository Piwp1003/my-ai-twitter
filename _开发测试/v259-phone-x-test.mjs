// 259：小手机里「推特」= 主页 + 私信（聊天）合在一起
import { chromium } from 'playwright';
import { launchBrowser, fileUrl } from './_launch.mjs';
import path from 'path';
const root = process.cwd();
const browser = await launchBrowser(chromium);
const results = []; const check = (n, ok, e = '') => results.push({ n, ok: !!ok, e });
const page = await (await browser.newContext({ viewport: { width: 390, height: 844 } })).newPage();
const errs = []; page.on('pageerror', e => errs.push(e.message));
await page.route(/^https?:\/\//, r => r.abort());
await page.goto(fileUrl(path.join(root, 'index.html')));
await page.waitForFunction(() => window.__guyuBooted && window.gyPmSet, { timeout: 20000 });
await page.evaluate(() => { myCharacters.length = 0; myCharacters.push({ id: 9101, name: '沈之遥', persona: 'x', worldbooks: [] }); globalChats['9101'] = [{ sender: 9101, text: '在吗', timestamp: Date.now() }]; });
await page.evaluate(() => gyPmSet(true)); await page.waitForTimeout(600);
const vis = s => page.evaluate(s => { const e = document.querySelector(s); if (!e) return false; const cs = getComputedStyle(e); return cs.display !== 'none' && cs.visibility !== 'hidden'; }, s);
check('桌面上没有单独的「聊天」图标', await page.evaluate(() => !document.querySelector('#gyPmHome .pm-app[data-pmapp="chat"]:not([data-where="lib"])') && !!document.querySelector('#gyPmHome .pm-app[data-pmapp="home"]')));
await page.evaluate(() => gyPmOpen('home')); await page.waitForTimeout(700);
check('打开推特：底下有推特那样的标签', await vis('#gyPmX'));
await page.evaluate(() => gyPmXGo('dm')); await page.waitForTimeout(500);
const v = await page.evaluate(() => ({ chat: document.getElementById('view-chat') && getComputedStyle(document.getElementById('view-chat')).display !== 'none', on: document.querySelector('#gyPmX span.on') && document.querySelectorAll('#gyPmX span')[3] === document.querySelector('#gyPmX span.on') }));
check('点「私信」：就是原来的聊天列表', v.chat && v.on, JSON.stringify(v));
await page.evaluate(() => { switchChatSession('9101'); }); await page.waitForTimeout(700);
check('进到一个人的聊天：标签收起来（不挡输入框）', !(await vis('#gyPmX')));
await page.evaluate(() => gyPmBack()); await page.waitForTimeout(500);
check('退回私信列表：标签回来', await vis('#gyPmX'));
await page.evaluate(() => gyPmXGo('home')); await page.waitForTimeout(400);
check('点「主页」：回谷雨主页', await page.evaluate(() => getComputedStyle(document.getElementById('view-home')).display !== 'none'));
await page.evaluate(() => { gyPmHome(); }); await page.waitForTimeout(400);
check('回桌面：标签不见', !(await vis('#gyPmX')));
await page.evaluate(() => gyPmSet(false)); await page.waitForTimeout(400);
check('关小手机：谷雨原样', !(await vis('#gyPmX')) && !(await page.evaluate(() => document.body.classList.contains('gyphm'))));
await browser.close();
const pass = results.filter(x => x.ok).length;
console.log('\n===== 259 小手机推特 =====');
results.forEach(x => console.log(`${x.ok ? '✅' : '❌'} ${x.n}${x.ok ? '' : ' ' + x.e}`));
if (errs.length) console.log('⚠️ ' + [...new Set(errs)].slice(0, 8).join('\n'));
console.log(`\n${pass}/${results.length} 通过`);
process.exit(pass === results.length ? 0 : 1);
