// 262：推特蓝色 / 黑色两版、书签、X 个人主页
import { chromium } from 'playwright';
import { launchBrowser, fileUrl } from './_launch.mjs';
import path from 'path';
const root = process.cwd(); const shot = process.argv.includes('--shot');
const browser = await launchBrowser(chromium);
const results = []; const check = (n, ok, e = '') => results.push({ n, ok: !!ok, e });
const page = await (await browser.newContext({ viewport: { width: 390, height: 844 } })).newPage();
const errs = []; page.on('pageerror', e => errs.push(e.message));
await page.route(/^https?:\/\//, r => r.abort());
await page.goto(fileUrl(path.join(root, 'index.html')));
await page.waitForFunction(() => window.__guyuBooted && window.gyPmSet, { timeout: 20000 });
await page.evaluate(() => {
  myCharacters.length = 0; myCharacters.push({ id: 9101, name: '沈之遥', handle: '@shen_zy', persona: 'x', worldbooks: [], isFollowing: true });
  globalChats['9101'] = [{ sender: 9101, text: '在吗', timestamp: Date.now() - 6e4 }, { sender: 'me', text: '在呀', timestamp: Date.now() - 3e4 }];
  globalPosts.unshift({ id: 'p_t1', char: { id: 9101, name: '沈之遥', handle: '@shen_zy' }, text: '今天的晚霞很好看，想拍给你。', timestamp: Date.now() - 3e5, stats: { likes: 12, comments: 3, retweets: 1, views: 99 } });
  try { renderPosts(); } catch (e) {}
});
await page.evaluate(() => gyPmSet(true)); await page.waitForTimeout(600);
await page.evaluate(() => gyPmOpen('home')); await page.waitForTimeout(900);
const col = s => page.evaluate(s => { const e = document.querySelector(s); return e ? getComputedStyle(e).backgroundColor : ''; }, s);
check('默认蓝色版：发帖圆按钮是推特蓝', /29, 155, 240/.test(await col('#fabPost') || await col('.fab-btn')), await col('#fabPost'));
check('推文操作栏里有书签键', await page.evaluate(() => !!document.querySelector('#feedSection .pa-bm')));
if (shot) await page.screenshot({ path: '_tmp/x-blue-home.png' });
await page.evaluate(() => document.querySelector('#feedSection .pa-bm').click()); await page.waitForTimeout(300);
check('点书签：进了书签（回忆相册里有这条推文）', await page.evaluate(() => memoryAlbum.some(m => m.type === 'post' && m.refId === 'p_t1')));
await page.evaluate(() => document.querySelector('#gyPmXHead .xa').click()); await page.waitForTimeout(400);
check('点左上头像：出来侧边抽屉', await page.evaluate(() => !!document.querySelector('#gyPmXDr.on .pane')));
if (shot) await page.screenshot({ path: '_tmp/x-blue-drawer.png' });
await page.evaluate(() => [...document.querySelectorAll('#gyPmXDr .li')].find(x => /书签/.test(x.textContent)).click()); await page.waitForTimeout(500);
check('书签页列出那条推文', await page.evaluate(() => /晚霞/.test((document.getElementById('gyPmXBmPg') || {}).textContent || '')));
if (shot) await page.screenshot({ path: '_tmp/x-blue-bm.png' });
await page.evaluate(() => document.querySelector('#gyPmXBmPg .ta i').click()); await page.waitForTimeout(300);
check('书签页里点掉：没了', await page.evaluate(() => !memoryAlbum.some(m => m.type === 'post' && m.refId === 'p_t1') && /只有你看得见/.test(document.getElementById('gyPmXBmPg').textContent)));
await page.evaluate(() => gyPmXBookmarks(false));
await page.evaluate(() => switchMainView('profile', 9101)); await page.waitForTimeout(700);
check('资料页也是推特样式', await page.evaluate(() => document.body.classList.contains('gyphm-xp')));
if (shot) await page.screenshot({ path: '_tmp/x-blue-prof.png' });
await page.evaluate(() => { gyPmXThemeSet('black'); }); await page.waitForTimeout(600);
check('换黑色版：还是白底', /255, 255, 255/.test(await col('#view-profile')), await col('#view-profile'));
if (shot) await page.screenshot({ path: '_tmp/x-black-prof.png' });
await page.evaluate(() => gyPmXGo('home')); await page.waitForTimeout(700);
check('黑色版主页：发帖键是黑的', /15, 20, 25/.test(await col('#fabPost') || await col('.fab-btn')), await col('#fabPost'));
if (shot) await page.screenshot({ path: '_tmp/x-black-home.png' });
await page.evaluate(() => { gyPmXGo('dm'); switchChatSession('9101'); }); await page.waitForTimeout(800);
check('黑色版私信：我的气泡是黑的', /15, 20, 25/.test(await col('#chatMessagesArea .chat-bubble.me')), await col('#chatMessagesArea .chat-bubble.me'));
if (shot) await page.screenshot({ path: '_tmp/x-black-dm.png' });
await page.evaluate(() => { gyPmXThemeSet('blue'); }); await page.waitForTimeout(600);
check('换回蓝色：我的气泡是蓝的', /29, 155, 240/.test(await col('#chatMessagesArea .chat-bubble.me')));
if (shot) await page.screenshot({ path: '_tmp/x-blue-dm.png' });
await page.evaluate(() => gyPmSet(false)); await page.waitForTimeout(400);
check('关小手机：书签键不显示', await page.evaluate(() => { const b = document.querySelector('.pa-bm'); return !b || getComputedStyle(b).display === 'none'; }));
await browser.close();
const pass = results.filter(x => x.ok).length;
console.log('\n===== 262 推特配色 / 书签 / 个人主页 =====');
results.forEach(x => console.log(`${x.ok ? '✅' : '❌'} ${x.n}${x.ok ? '' : ' ' + x.e}`));
if (errs.length) console.log('⚠️ ' + [...new Set(errs)].slice(0, 8).join('\n'));
console.log(`\n${pass}/${results.length} 通过`);
process.exit(pass === results.length ? 0 : 1);
